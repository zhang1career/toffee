#!/usr/bin/env node

/**
 * 生成 iOS 原生代码配置文件
 * 将 TypeScript 配置转换为 Objective-C 头文件
 */

const fs = require('fs');
const path = require('path');

// 配置常量（与 src/index.ts 保持一致）
const METRO_CONFIG = {
  defaultPort: 8081,
  defaultHost: 'localhost',
  bundleRoot: 'index',
  bundleName: 'main',
  bundleExtension: 'jsbundle',
};

const APP_CONFIG = {
  moduleName: 'EchoNative',
  displayName: 'Echo',
};

const STORAGE_KEYS = {
  deviceId: 'echo_device_id',
  firstLaunch: 'echo_first_launch',
  metroPort: 'RCT_METRO_PORT',
};

const PERMISSIONS = {
  microphone: {
    description: 'Echo 需要访问麦克风以录制语音消息并与其他用户分享。',
  },
  location: {
    description: '',
  },
};

// 错误码和错误信息
const ERROR_CODES = {
  BUNDLE_URL_NOT_AVAILABLE: 2001,
  MAIN_BUNDLE_NOT_FOUND: 2003,
  AUDIO_SIMULATOR_NOT_SUPPORTED: 3005,
};

// 生成 Objective-C 头文件内容
function generateIOSHeader() {
  return `//
// EchoConfig.h
// Auto-generated from packages/config
// DO NOT EDIT MANUALLY - This file is generated by 'npm run generate-ios'
//

#import <Foundation/Foundation.h>

NS_ASSUME_NONNULL_BEGIN

// Metro Bundler 配置
extern NSInteger const ECHO_METRO_DEFAULT_PORT;
extern NSString * const ECHO_METRO_DEFAULT_HOST;
extern NSString * const ECHO_METRO_BUNDLE_ROOT;
extern NSString * const ECHO_METRO_BUNDLE_NAME;
extern NSString * const ECHO_METRO_BUNDLE_EXTENSION;

// 应用配置
extern NSString * const ECHO_APP_MODULE_NAME;
extern NSString * const ECHO_APP_DISPLAY_NAME;

// 存储键名
extern NSString * const ECHO_STORAGE_KEY_DEVICE_ID;
extern NSString * const ECHO_STORAGE_KEY_FIRST_LAUNCH;
extern NSString * const ECHO_STORAGE_KEY_METRO_PORT;

// 错误码
extern NSInteger const ECHO_ERROR_BUNDLE_URL_NOT_AVAILABLE;
extern NSInteger const ECHO_ERROR_MAIN_BUNDLE_NOT_FOUND;
extern NSInteger const ECHO_ERROR_AUDIO_SIMULATOR_NOT_SUPPORTED;

NS_ASSUME_NONNULL_END
`;
}

// 生成 Objective-C 实现文件内容
function generateIOSImplementation() {
  return `//
// EchoConfig.m
// Auto-generated from packages/config
// DO NOT EDIT MANUALLY - This file is generated by 'npm run generate-ios'
//

#import "EchoConfig.h"

// Metro Bundler 配置
NSInteger const ECHO_METRO_DEFAULT_PORT = ${METRO_CONFIG.defaultPort};
NSString * const ECHO_METRO_DEFAULT_HOST = @"${METRO_CONFIG.defaultHost}";
NSString * const ECHO_METRO_BUNDLE_ROOT = @"${METRO_CONFIG.bundleRoot}";
NSString * const ECHO_METRO_BUNDLE_NAME = @"${METRO_CONFIG.bundleName}";
NSString * const ECHO_METRO_BUNDLE_EXTENSION = @"${METRO_CONFIG.bundleExtension}";

// 应用配置
NSString * const ECHO_APP_MODULE_NAME = @"${APP_CONFIG.moduleName}";
NSString * const ECHO_APP_DISPLAY_NAME = @"${APP_CONFIG.displayName}";

// 存储键名
NSString * const ECHO_STORAGE_KEY_DEVICE_ID = @"${STORAGE_KEYS.deviceId}";
NSString * const ECHO_STORAGE_KEY_FIRST_LAUNCH = @"${STORAGE_KEYS.firstLaunch}";
NSString * const ECHO_STORAGE_KEY_METRO_PORT = @"${STORAGE_KEYS.metroPort}";

// 错误码
NSInteger const ECHO_ERROR_BUNDLE_URL_NOT_AVAILABLE = ${ERROR_CODES.BUNDLE_URL_NOT_AVAILABLE};
NSInteger const ECHO_ERROR_MAIN_BUNDLE_NOT_FOUND = ${ERROR_CODES.MAIN_BUNDLE_NOT_FOUND};
NSInteger const ECHO_ERROR_AUDIO_SIMULATOR_NOT_SUPPORTED = ${ERROR_CODES.AUDIO_SIMULATOR_NOT_SUPPORTED};
`;
}

// 生成 JSON 配置文件（供其他工具使用）
function generateJSONConfig() {
  return JSON.stringify({
    metro: METRO_CONFIG,
    app: APP_CONFIG,
    storage: STORAGE_KEYS,
    permissions: PERMISSIONS,
    errors: ERROR_CODES,
  }, null, 2);
}

// 主函数
function main() {
  const outputDir = path.join(__dirname, '../../ios-config');
  const iosDir = path.join(outputDir, 'ios');
  
  // 创建输出目录
  if (!fs.existsSync(outputDir)) {
    fs.mkdirSync(outputDir, { recursive: true });
  }
  if (!fs.existsSync(iosDir)) {
    fs.mkdirSync(iosDir, { recursive: true });
  }
  
  // 生成文件
  const headerContent = generateIOSHeader();
  const implContent = generateIOSImplementation();
  const jsonContent = generateJSONConfig();
  
  fs.writeFileSync(path.join(iosDir, 'EchoConfig.h'), headerContent);
  fs.writeFileSync(path.join(iosDir, 'EchoConfig.m'), implContent);
  fs.writeFileSync(path.join(outputDir, 'config.json'), jsonContent);
  
  console.log('✅ iOS 配置文件生成成功:');
  console.log(`   - ${path.join(iosDir, 'EchoConfig.h')}`);
  console.log(`   - ${path.join(iosDir, 'EchoConfig.m')}`);
  console.log(`   - ${path.join(outputDir, 'config.json')}`);
  console.log('\n💡 使用提示:');
  console.log('   将 EchoConfig.h 和 EchoConfig.m 复制到 iOS 项目中使用');
}

main();

